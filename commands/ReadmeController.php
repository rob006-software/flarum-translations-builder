/**
 * Class ReadmeController.
 *
 * @author Robert Korulczyk <robert@korulczyk.pl>
 */
final class ReadmeController extends ConsoleController {

	private const GROUPS = [
		'all',
		'flarum',
		'fof',
		'various',
		'premium',
	];

	/** Content of git config files in language packs, generated by `readme/update-git-files`. */
	private const GIT_FILES = [
		'.gitattributes' => ".gitattributes export-ignore\n.gitignore export-ignore\n",
		'.gitignore' => "/composer.lock\n/vendor/\n",
	];

	public $defaultAction = 'update';

	public function options($actionID) {
		return array_merge(parent::options($actionID), [
			'commit',
			'push',
			'verbose',
			'frequency',
			'update',
		]);
	}

	public function actionUpdate(string $configFile = '@app/translations/config.php') {
		$translations = $this->getTranslations($configFile);
		$token = __METHOD__ . '#' . $translations->getHash();
		if ($this->isLimited($token)) {
			return;
		}
		$readme = file_get_contents($translations->getDir() . '/README.md');
		$summary = file_get_contents($translations->getDir() . '/status/summary.md');
		$licenses = file_get_contents($translations->getDir() . '/status/licenses.md');

		if (
			strpos($readme, '<!-- languages-list-start -->') !== false
			&& strpos($readme, '<!-- languages-list-stop -->') !== false
		) {
			$readmeGenerator = new MainReadmeGenerator();
			$readme = $this->replaceBetween(
				'<!-- languages-list-start -->',
				'<!-- languages-list-stop -->',
				$readme,
				$readmeGenerator->generateLanguagesList($this->getLanguageSubsplits($translations))
			);
		}

		foreach (self::GROUPS as $group) {
			if (
				strpos($readme, "<!-- {$group}-extensions-list-start -->") !== false
				&& strpos($readme, "<!-- {$group}-extensions-list-stop -->") !== false
			) {
				$readmeGenerator = new MainReadmeGenerator();
				$summaryGenerator = new SummaryGenerator();
				$licensesGenerator = new LicenseSummaryGenerator();

				foreach ($translations->getExtensionsComponents() as $component) {
					$extension = Yii::$app->extensionsRepository->getExtension($component->getId());
					if ($extension !== null && $this->isValidForGroup($extension, $group)) {
						$readmeGenerator->addExtension($extension);
						$summaryGenerator->addExtension($extension);
						$licensesGenerator->addExtension($extension);
					}
				}

				$readme = $this->replaceBetween(
					"<!-- {$group}-extensions-list-start -->",
					"<!-- {$group}-extensions-list-stop -->",
					$readme,
					$readmeGenerator->generate()
				);
				if (
					strpos($summary, "<!-- {$group}-extensions-list-start -->") !== false
					&& strpos($summary, "<!-- {$group}-extensions-list-stop -->") !== false
				) {
					$summary = $this->replaceBetween(
						"<!-- {$group}-extensions-list-start -->",
						"<!-- {$group}-extensions-list-stop -->",
						$summary,
						$summaryGenerator->generate()
					);
				}
				if (
					strpos($licenses, "<!-- {$group}-extensions-list-start -->") !== false
					&& strpos($licenses, "<!-- {$group}-extensions-list-stop -->") !== false
				) {
					$licenses = $this->replaceBetween(
						"<!-- {$group}-extensions-list-start -->",
						"<!-- {$group}-extensions-list-stop -->",
						$licenses,
						$licensesGenerator->generate()
					);
				}
			}
		}

		file_put_contents($translations->getDir() . '/README.md', $readme);
		file_put_contents($translations->getDir() . '/status/summary.md', $summary);
		file_put_contents($translations->getDir() . '/status/licenses.md', $licenses);
		$flarumVersion = FlarumVersion::lineName();
		$this->postProcessRepository(
			$translations->getRepository(),
			"[{$flarumVersion}] Update list of supported extensions"
		);

		$languagePacksGenerator = new LanguagePacksSummaryGenerator($this->getLanguageSubsplits($translations));
		file_put_contents($translations->getDir() . '/status/language-packs.md', $languagePacksGenerator->generate());
		$flarumVersion = FlarumVersion::lineName();
		$this->postProcessRepository(
			$translations->getRepository(),
			"[{$flarumVersion}] Update list of language packs"
		);

		$this->updateLimit($token);
	}

	public function actionUpdateSubsplits(array $subsplits = [], string $configFile = '@app/translations/config.php') {
		$translations = $this->getTranslations($configFile);
		$token = __METHOD__ . '#' . $translations->getTranslationsHash() . $translations->getHash();
		if ($this->isLimited($token)) {
			return;
		}

		if (empty($subsplits)) {
			$subsplits = $translations->getSubsplits();
		} else {
			foreach ($subsplits as $key => $subsplitId) {
				$subsplits[$key] = $translations->getSubsplit($subsplitId);
			}
		}

		$hasErrors = false;
		foreach ($subsplits as $subsplit) {
			$subsplitToken = __METHOD__ . '#' . $subsplit->getId() . '#' . $subsplit->getTranslationsHash($translations);
			if ($this->isLimited($subsplitToken)) {
				continue;
			}

			try {
				// acquire repository lock outside of try/finally below - there is nothing to release if this fails
				$repository = $subsplit->getRepository();
			} catch (Throwable $exception) {
				$hasErrors = true;
				$this->reportError($subsplit, $exception);
				continue;
			}

			try {
				$this->updateSubsplitReadme($translations, $subsplit);
			} catch (Throwable $exception) {
				$hasErrors = true;
				$this->reportError($subsplit, $exception);
				continue;
			} finally {
				Yii::$app->locks->releaseRepoLock($repository->getPath());
			}

			$this->updateLimit($subsplitToken);
		}

		// do not mark the whole run as done if some subsplits failed - they should be retried on the next run
		if (!$hasErrors) {
			$this->updateLimit($token);
		}
	}

	/**
	 * Creates or updates `AGENTS.md` and `CLAUDE.md` in language packs, which redirect AI agents to translations repository.
	 * Existing files which were not generated by this command are never overwritten. Not scheduled - run it manually
	 * after changing the template or adding a language pack.
	 */
	public function actionUpdateAgents(array $subsplits = [], string $configFile = '@app/translations/config.php') {
		$translations = $this->getTranslations($configFile);
		$this->updateSubsplitsFiles(
			$this->resolveSubsplits($translations, $subsplits),
			'AGENTS.md',
			'Update instructions for AI agents',
			static function (Subsplit $subsplit, Repository $repository) {
				$generator = new AgentsInstructionsGenerator($subsplit);
				$files = [
					AgentsInstructionsGenerator::AGENTS_FILE => $generator->generateAgentsMd(),
					AgentsInstructionsGenerator::CLAUDE_FILE => AgentsInstructionsGenerator::generateClaudeMd(),
				];
				foreach ($files as $fileName => $content) {
					$path = $repository->getPath() . '/' . $fileName;
					if (file_exists($path) && !AgentsInstructionsGenerator::isGenerated($fileName, file_get_contents($path))) {
						Yii::warning("{$subsplit->getId()}: $fileName was not generated by builder - skipped.");
						echo Console::renderColoredString("%y{$subsplit->getId()}: $fileName was not generated by builder - skipped.%n"), "\n";
						continue;
					}
					file_put_contents($path, $content);
				}
			}
		);
	}

	/**
	 * Creates or updates `.gitattributes` and `.gitignore` in language packs. Existing files are always overwritten.
	 * Not scheduled - run it manually after changing the template or adding a language pack.
	 */
	public function actionUpdateGitFiles(array $subsplits = [], string $configFile = '@app/translations/config.php') {
		$translations = $this->getTranslations($configFile);
		$this->updateSubsplitsFiles(
			$this->resolveSubsplits($translations, $subsplits),
			'.gitattributes and .gitignore',
			'Update .gitattributes and .gitignore',
			static function (Subsplit $subsplit, Repository $repository) {
				foreach (self::GIT_FILES as $fileName => $content) {
					file_put_contents($repository->getPath() . '/' . $fileName, $content);
				}
			}
		);
	}

	/**
	 * Overwrites `composer.json` in language packs with version generated from builder config. Only `flarum/core`
	 * constraint and icon are preserved from existing file. Not scheduled - run it manually after changing the template,
	 * languages or subsplits config.
	 */
	public function actionUpdateComposer(array $subsplits = [], string $configFile = '@app/translations/config.php') {
		$translations = $this->getTranslations($configFile);
		$this->updateSubsplitsFiles(
			$this->resolveSubsplits($translations, $subsplits),
			ComposerJsonGenerator::FILE,
			'Update composer.json',
			static function (Subsplit $subsplit, Repository $repository) use ($translations) {
				$path = $repository->getPath() . '/' . ComposerJsonGenerator::FILE;
				$current = file_exists($path)
					? json_decode(file_get_contents($path), true, 512, JSON_THROW_ON_ERROR)
					: [];
				$generator = new ComposerJsonGenerator($subsplit, $translations, $current);
				file_put_contents($path, $generator->generate());
			}
		);
	}

	private function updateSubsplitReadme(Translations $translations, Subsplit $subsplit): void {
		$subsplit->getRepository()->update();
		$readme = file_get_contents($subsplit->getDir() . '/README.md');
		$changed = false;
		foreach (self::GROUPS as $group) {
			if (
				strpos($readme, "<!-- {$group}-extensions-list-start -->") !== false
				&& strpos($readme, "<!-- {$group}-extensions-list-stop -->") !== false
			) {
				$generator = $subsplit->createReadmeGenerator($translations);
				foreach ($translations->getExtensionsComponents() as $component) {
					if ($subsplit->isValidForComponent($component) && $subsplit->hasTranslationForComponent($component)) {
						$extension = Yii::$app->extensionsRepository->getExtension($component->getId());
						if ($extension !== null && $this->isValidForGroup($extension, $group)) {
							$generator->addExtension($extension);
						}
					}
				}

				$changed = true;
				$readme = $this->replaceBetween(
					"<!-- {$group}-extensions-list-start -->",
					"<!-- {$group}-extensions-list-stop -->",
					$readme,
					$generator->generate()
				);
			}
		}

		if ($changed) {
			file_put_contents($subsplit->getDir() . '/README.md', $readme);
			$this->postProcessRepository(
				$subsplit->getRepository(),
				'Update translations status in README'
			);
		}
	}

	/**
	 * @return LanguageSubsplit[] Language subsplits (main variants for multi-language ones), indexed by language.
	 */
	private function getLanguageSubsplits(Translations $translations): array {
		$languageSubsplits = [];
		foreach ($translations->getSubsplits() as $subsplit) {
			if ($subsplit instanceof MultiLanguageSubsplit) {
				$subsplit = $subsplit->getMainVariant();
			}
			if ($subsplit instanceof LanguageSubsplit) {
				$languageSubsplits[$subsplit->getLanguage()] = $subsplit;
			}
		}

		return $languageSubsplits;
	}

	private function reportError(Subsplit $subsplit, Throwable $exception): void {
		Yii::warning("An error occurred while updating README for {$subsplit->getId()} subsplit: {$exception->getMessage()}");
		Yii::error($exception);
		echo Console::renderColoredString("%r{$subsplit->getId()}: {$exception->getMessage()}%n"), "\n";
	}

	private function replaceBetween(string $begin, string $end, string $string, string $replacement): string {
		$positionBegin = strpos($string, $begin);
		if ($positionBegin === false) {
			throw new InvalidArgumentException('$string does not contain ' . readable::value($begin) . '.');
		}
		$positionEnd = strpos($string, $end, $positionBegin);
		if ($positionEnd === false) {
			throw new InvalidArgumentException('$string does not contain ' . readable::value($end) . '.');
		}

		return substr($string, 0, $positionBegin) . $begin . $replacement . substr($string, $positionEnd);
	}

	private function isValidForGroup(Extension $extension, string $group): bool {
		if ($group === 'all') {
			return true;
		}

		if ($group === 'premium') {
			return $extension instanceof PremiumExtension;
		}
		if ($extension instanceof PremiumExtension) {
			return false;
		}

		if (in_array($group, ['flarum', 'fof'], true)) {
			return $group === $extension->getVendor();
		}
		return !in_array($extension->getVendor(), ['flarum', 'fof'], true);
	}
}

declare(strict_types=1);

namespace app\components\readme;

use app\helpers\FlarumVersion;
use app\models\LanguageSubsplit;
use app\models\MultiLanguageSubsplit;
use app\models\Subsplit;
use Dont\DontCall;
use Dont\DontCallStatic;
use Dont\DontGet;
use Dont\DontSet;
use function implode;
use function strncmp;
use function strlen;
use function trim;

/**
 * Class AgentsInstructionsGenerator.
 *
 * Generates `AGENTS.md` and `CLAUDE.md` for language pack repository. These files redirect AI agents from generated
 * YAML files in language pack to JSON files in translations repository.
 *
 * @see https://github.com/rob006-software/flarum-translations-builder/issues/60
 *
 * @author Robert Korulczyk <robert@korulczyk.pl>
 */
final class AgentsInstructionsGenerator {

	use DontCall;
	use DontCallStatic;
	use DontGet;
	use DontSet;

	public const AGENTS_FILE = 'AGENTS.md';
	public const CLAUDE_FILE = 'CLAUDE.md';

	/** First line of generated `AGENTS.md` - files without it were not generated by builder and are never overwritten. */
	private const MARKER = '<!-- This file is generated by https://github.com/rob006-software/flarum-translations-builder - do not edit. -->';
	private const TRANSLATIONS_REPOSITORY = 'https://github.com/rob006-software/flarum-translations';

	private $subsplit;

	public function __construct(Subsplit $subsplit) {
		$this->subsplit = $subsplit;
	}

	public static function isGenerated(string $fileName, string $content): bool {
		if ($fileName === self::CLAUDE_FILE) {
			return trim($content) === trim(self::generateClaudeMd());
		}

		return strncmp($content, self::MARKER, strlen(self::MARKER)) === 0;
	}

	public static function generateClaudeMd(): string {
		return "@AGENTS.md\n";
	}

	public function generateAgentsMd(): string {
		$branch = FlarumVersion::branch();
		$line = FlarumVersion::lineName();
		$weblateProject = FlarumVersion::weblateProject();
		$repository = self::TRANSLATIONS_REPOSITORY;
		$mapping = [];
		$weblateLinks = [];
		foreach ($this->getLanguageSubsplits() as $subsplit) {
			$path = trim($subsplit->getPath(), '/');
			$language = $subsplit->getLanguage();
			$mapping[] = "- `$path/<component>.yml` -> `translations/$language/<component>.json`";
			$weblateLinks[] = "https://weblate.rob006.net/languages/$language/$weblateProject/";
		}
		$mapping = implode("\n", $mapping);
		$weblateLinks = implode(', ', $weblateLinks);
		$marker = self::MARKER;

		return <<<MD
			$marker

			# Instructions for AI agents

			Translation files (`*.yml`) in this repository are generated from [rob006-software/flarum-translations]($repository) -
			any change made here is overwritten on the next export. **Do not open pull requests editing translation files in
			this repository.**

			To fix a translation, open a pull request in [rob006-software/flarum-translations]($repository) instead, targeting
			the `$branch` branch (this branch of the language pack is for Flarum $line), and follow `AGENTS.md` of that
			repository. Files map as follows (`<component>` is the same in both places, like `core` or `flarum-tags`):

			$mapping

			If the fix is for a phrase that is missing or wrong in English, or for a bug in the extension itself, it belongs to
			the extension repository, not to translations.

			People who prefer to translate in the browser can use Weblate: $weblateLinks (AI agents can't access it).

			`CHANGELOG.md` and the translation status in `README.md` are also generated. Other files (like `composer.json` or
			`extend.php`) are maintained in this repository as usual.

			MD;
	}

	/**
	 * @return LanguageSubsplit[] Subsplit itself, or variants for multi-language subsplit.
	 */
	private function getLanguageSubsplits(): array {
		return $this->subsplit instanceof MultiLanguageSubsplit ? $this->subsplit->getVariants() : [$this->subsplit];
	}
}
